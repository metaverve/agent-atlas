import { chromium } from "playwright";
const base = process.argv[2] || "http://localhost:3123"; const out = process.argv[3] || "qa";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = []; p.on("pageerror", e => errs.push(e.message)); p.on("console", m => m.type() === "error" && errs.push(m.text()));
await p.goto(base, { waitUntil: "networkidle" }); await p.waitForTimeout(2500);
const total = await p.textContent('[data-testid=count]');
await p.screenshot({ path: `${out}/01-home.png`, fullPage: false });
await p.fill('[data-testid=search]', 'browsr automaton'); await p.waitForTimeout(400);
const s = await p.textContent('[data-testid=count]'); const first = await p.textContent('[data-testid=card] h3');
await p.screenshot({ path: `${out}/02-search.png` });
await p.fill('[data-testid=search]', ''); await p.click('text=Coding'); await p.selectOption('select[aria-label=license]', 'true'); await p.fill('input[aria-label="min stars"]', '10000'); await p.waitForTimeout(300);
const f = await p.textContent('[data-testid=count]'); await p.screenshot({ path: `${out}/03-filter.png` });
await p.click('button:has-text("Reset")'); await p.click('button:has-text("Table")'); await p.waitForTimeout(300); await p.screenshot({ path: `${out}/04-table.png` });
await p.click('button:has-text("Cards")');
await p.locator('g[data-node="langchain"]').click({ force: true }); await p.waitForTimeout(500);
const g = await p.textContent('[data-testid=count]'); const tf = await p.textContent('[data-testid=tool-filter]');
await p.screenshot({ path: `${out}/05-graph-click.png` });
const api = await (await p.request.get(`${base}/api/agents?useCase=Coding&oss=true&minStars=10000&limit=3`)).json();
const mcp = await (await p.request.post(`${base}/api/mcp`, { data: { jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "get_stack", arguments: { id: "chroma" } } } })).json();
const spec = (await p.request.get(`${base}/api/openapi.json`)).status(); const llms = (await p.request.get(`${base}/llms.txt`)).status();
await p.goto(`${base}/docs`); await p.screenshot({ path: `${out}/06-docs.png`, fullPage: true });
console.log(JSON.stringify({ total, s, first, f, g, tf, apiTotal: api.total, apiStats: api.stats.mode, mcpNodes: mcp.result.structuredContent.nodes.length, spec, llms, errs }, null, 1));
await b.close();
